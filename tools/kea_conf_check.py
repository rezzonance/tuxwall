#!/usr/bin/env python3
"""Kea config reader/writer checks (www/includes/kea_conf.py), sandboxed:

  python3 tools/kea_conf_check.py

Kea accepts '//' and '#' line comments, trailing comments and '/* */'
blocks; tuxwall-install.sh writes a '// Generated by ...' header. Covers:
comment stripping only outside strings (URLs, '#' in hostnames, escaped
quotes), the installer's real header (kea_json run in bash), header
split/preservation and the one-time dashboard edit mark, the atomic write
(owner/mode kept, no temp file left, round trip), and every consumer:
api_server _read_kea/_write_kea + the reservation add/edit/delete flow
(Kea reload stubbed), router_static/kea_reservations/build_reservations,
topology._read_kea, assign_plan's Kea render, fw_lint's reservation scan,
and the installer's kea_is_replaceable decision. Nothing touches /etc.
"""
import importlib.util
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT_DIR, "www", "includes")
INSTALLER = os.path.join(ROOT_DIR, "tuxwall-install.sh")
sys.dont_write_bytecode = True
sys.path.insert(0, INC)

import kea_conf as K  # noqa: E402

PASS = FAIL = 0


def check(cond, name):
    global PASS, FAIL
    if cond:
        PASS += 1
    else:
        FAIL += 1
        print("FAIL:", name)


def raises(fn):
    try:
        fn()
    except Exception as exc:
        return exc
    return None


TMP = tempfile.mkdtemp(prefix="kea-conf-check-")

COMMENTED = r'''// Generated by the TuxWall installer on 2026-11-21 02:33:00. Managed from the DHCP page afterwards.
# second header line
/* a block
   header */

{
  "Dhcp4": {   // trailing comment
    # whole-line hash comment
    "interfaces-config": { "interfaces": [ "eth1" ] },  # trailing hash
    /* inline block */ "valid-lifetime": 7200,
    "option-data": [
      { "name": "domain-name", "data": "lan#1.example" },
      { "name": "boot-file-name", "data": "http://boot.example/ipxe//x#frag" },
      { "name": "v4-captive-portal", "data": "https://portal/*not a comment*/" },
      { "name": "quoted", "data": "say \"hi\" // still a string \\" }
    ],
    /*
     * multi-line
     */
    "subnet4": [
      { "id": 1, "subnet": "192.168.100.0/24", "interface": "eth1",
        "pools": [ { "pool": "192.168.100.100 - 192.168.100.200" } ],
        "reservations": [
          { "hw-address": "aa:bb:cc:dd:ee:01", "ip-address": "192.168.100.50", "hostname": "x" }
          // { "hw-address": "aa:bb:cc:dd:ee:02", "ip-address": "192.168.100.99" }
        ] }
    ]
  }
}
'''

try:
    # ---------------------------------------------------------------- parsing
    doc = K.loads(COMMENTED)
    d4 = doc["Dhcp4"]
    opts = {o["name"]: o["data"] for o in d4["option-data"]}
    check(opts["domain-name"] == "lan#1.example", "'#' inside a string kept: %r" % opts["domain-name"])
    check(opts["boot-file-name"] == "http://boot.example/ipxe//x#frag", "URL with // and # kept")
    check(opts["v4-captive-portal"] == "https://portal/*not a comment*/", "/* */ inside a string kept")
    check(opts["quoted"] == 'say "hi" // still a string \\', "escaped quotes/backslash kept: %r" % opts["quoted"])
    check(d4["valid-lifetime"] == 7200 and d4["interfaces-config"]["interfaces"] == ["eth1"],
          "trailing // # and inline /* */ comments stripped")
    res = d4["subnet4"][0]["reservations"]
    check(len(res) == 1 and res[0]["ip-address"] == "192.168.100.50", "commented-out reservation ignored")
    stripped = K.strip_comments(COMMENTED)
    check(stripped.count("\n") == COMMENTED.count("\n") and len(stripped) == len(COMMENTED),
          "stripping keeps line numbers/offsets")
    plain = json.dumps({"a": "http://x//y#z", "b": [1, 2]})
    check(K.loads(plain) == json.loads(plain) and not K.has_comments(plain), "plain JSON unchanged")
    check(K.strip_comments(plain) == plain, "plain JSON text untouched by the stripper")
    check(isinstance(raises(lambda: K.loads('// only a comment\n{"a": }')), ValueError),
          "invalid JSON still raises ValueError")
    check(isinstance(raises(lambda: K.loads("")), ValueError), "empty text raises ValueError")
    check(K.loads('{"a": 1} /* unterminated') == {"a": 1}, "unterminated block comment runs to EOF")

    # ------------------------------------------------------- header handling
    head, rest = K.split_header(COMMENTED)
    check(head.startswith("// Generated by the TuxWall installer") and head.rstrip().endswith("header */"),
          "header = leading comment lines: %r" % head)
    check(rest.lstrip().startswith("{") and head + rest == COMMENTED, "header + rest == original")
    check(K.split_header(plain) == ("", plain), "no header on plain JSON")
    check(K.split_header('\n\n{"a": 1}')[0] == "", "blank lines alone are no header")
    h2, r2 = K.split_header('/* x */ {"a": 1}')
    check(h2 == "/* x */ " and K.loads(K.dumps({"a": 1}, h2)) == {"a": 1}, "same-line header comment")
    check(K.body_has_comments(COMMENTED) and not K.body_has_comments('// h\n{"a": "//"}'),
          "body comment detection (strings ignored)")

    out = K.dumps(doc, head)
    check(out.startswith(head) and K.EDIT_MARK in out.split("{", 1)[0], "installer header kept + edit mark added")
    check(K.loads(out) == doc, "dumps round trip")
    out2 = K.dumps(K.loads(out), K.split_header(out)[0])
    check(out2 == out and out2.count(K.EDIT_MARK) == 1, "second rewrite is byte-identical (mark added once)")
    custom = "// my own notes\n# more\n"
    check(K.dumps({"a": 1}, custom) == custom + '{\n    "a": 1\n}\n', "non-installer header kept verbatim, no mark")
    check(K.dumps({"a": 1}) == '{\n    "a": 1\n}\n', "no header -> plain indented JSON")

    # ---------------------------------------- installer's real kea_json output
    src = open(INSTALLER).read()
    mark = re.search(r'^INSTALLER_MARK="([^"]*)"', src, re.M).group(1)
    emark = re.search(r'^KEA_EDIT_MARK="([^"]*)"', src, re.M).group(1)
    check(mark == K.INSTALLER_MARK and emark == K.EDIT_MARK, "installer marks == kea_conf marks")
    fn = re.search(r"^kea_json\(\) \{.*?^KEA\n\}\n", src, re.M | re.S).group(0)
    gen = subprocess.run(
        ["bash", "-c", fn + 'INSTALLER_MARK="%s"; LAN=eth1; NET_CIDR=192.168.100.0/24; NET_POOL_LO=192.168.100.100;'
         ' NET_POOL_HI=192.168.100.200; NET_GW=192.168.100.1; DOMAIN=home.arpa; kea_json socket-name' % mark],
        capture_output=True, text=True, timeout=10).stdout
    check(gen.startswith("// " + mark), "installer kea_json starts with the // header")
    check(isinstance(raises(lambda: json.loads(gen)), ValueError), "installer output is not strict JSON (the bug)")
    gd = K.loads(gen)
    check(gd["Dhcp4"]["subnet4"][0]["subnet"] == "192.168.100.0/24", "installer output parses tolerantly")

    # ------------------------------------------------------- atomic write
    path = os.path.join(TMP, "kea-dhcp4.conf")
    with open(path, "w") as f:
        f.write(gen)
    os.chmod(path, 0o640)
    st0 = os.stat(path)
    gd["Dhcp4"]["subnet4"][0].setdefault("reservations", []).append(
        {"hw-address": "aa:bb:cc:dd:ee:01", "ip-address": "192.168.100.50", "hostname": "t"})
    K.write(path, gd)
    st1 = os.stat(path)
    txt = open(path).read()
    check(stat.S_IMODE(st1.st_mode) == 0o640 and (st1.st_uid, st1.st_gid) == (st0.st_uid, st0.st_gid),
          "write keeps mode/owner: %o" % stat.S_IMODE(st1.st_mode))
    check(st1.st_ino != st0.st_ino, "write replaces the file (atomic rename)")
    check(txt.startswith(gen.split("\n", 1)[0] + "\n") and K.EDIT_MARK in txt, "write keeps the header line")
    check(K.read(path) == gd, "write/read round trip")
    check(os.listdir(TMP) == ["kea-dhcp4.conf"], "no temp file left: %s" % os.listdir(TMP))
    K.write(path, gd)
    check(open(path).read() == txt, "rewrite is idempotent")
    check(isinstance(raises(lambda: K.write(path, {"bad": {1, 2}})), TypeError) and open(path).read() == txt,
          "unserialisable data: original file untouched")
    check(os.listdir(TMP) == ["kea-dhcp4.conf"], "no temp file left after a failed write")
    newp = os.path.join(TMP, "new.conf")
    K.write(newp, {"a": 1})
    check(stat.S_IMODE(os.stat(newp).st_mode) == 0o644 and K.read(newp) == {"a": 1}, "new file: 0644")
    os.unlink(newp)

    # ------------------------------------------------------- api_server
    spec = importlib.util.spec_from_file_location("api_server_keacheck", os.path.join(INC, "api_server.py"))
    A = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(A)
    check(A._kea_conf is not None, "api_server imported kea_conf")
    with open(path, "w") as f:
        f.write(COMMENTED)
    A.KEA_CONF = path
    reloads = []
    A._reload_kea = lambda: reloads.append(1)
    A.arp_online = lambda ip: False
    opened = []
    real_open = open

    def guard_open(p, *a, **kw):
        if str(p).startswith("/etc/kea"):
            opened.append(p)
        return real_open(p, *a, **kw)
    A.open = guard_open  # module-level open() lookups resolve here first
    A.__dict__["open"] = guard_open
    real_read = A._read_kea
    r = A.build_reservations()
    check(r["ok"] and [x["ip"] for x in r["reservations"]] == ["192.168.100.50"], "build_reservations: %r" % r)
    r = A.add_reservation({"ip": "192.168.100.51", "mac": "AA:BB:CC:DD:EE:02", "hostname": "new-host"})
    check(r["ok"] and len(r["reservations"]) == 2 and reloads == [1], "add_reservation on a commented file: %r" % r)
    txt = open(path).read()
    check(txt.startswith(head) and K.EDIT_MARK in txt, "add_reservation keeps the header")
    o = {x["name"]: x["data"] for x in K.read(path)["Dhcp4"]["option-data"]}
    check(o == opts, "strings with // and # survive the rewrite")
    rid = [x["id"] for x in r["reservations"] if x["ip"] == "192.168.100.51"][0]
    r = A.edit_reservation({"id": rid, "mac": "aa:bb:cc:dd:ee:03", "hostname": "renamed"})
    check([x["hostname"] for x in r["reservations"] if x["ip"] == "192.168.100.51"] == ["renamed"], "edit_reservation")
    r = A.delete_reservation({"id": rid})
    check([x["ip"] for x in r["reservations"]] == ["192.168.100.50"] and len(reloads) == 3, "delete_reservation")
    check(open(path).read().count(K.EDIT_MARK) == 1, "edit mark once after 3 rewrites")
    check(os.listdir(TMP) == ["kea-dhcp4.conf"], "api writes leave no temp file")
    # helpers that used to json.load the hard-coded path now go via _read_kea
    seen = []
    A._read_kea = lambda: (seen.append(1), K.read(path))[1]
    A._ROUTER_CACHE.update({"ts": 0, "data": None})
    kr = A.kea_reservations()
    check([x["ip"] for x in kr] == ["192.168.100.50"] and seen, "kea_reservations via the tolerant reader")
    seen.clear()
    A.router_static()
    check(seen, "router_static via the tolerant reader")
    A._read_kea = real_read
    check(not opened, "nothing under /etc/kea opened: %s" % opened)
    src_api = open(os.path.join(INC, "api_server.py")).read()
    check(len(re.findall(r'open\("/etc/kea/kea-dhcp4\.conf"', src_api)) == 0,
          "api_server: no direct strict open/json.load of kea-dhcp4.conf left")

    # ------------------------------------------------------- topology / assign_plan / fw_lint
    import topology as T
    T.KEA_CONF = path
    check(T._read_kea()["Dhcp4"]["subnet4"][0]["subnet"] == "192.168.100.0/24", "topology._read_kea tolerant")
    with open(path, "w") as f:
        f.write('// h\n{"Dhcp4": {"x": "a//b#c"}} trailing garbage')
    check(T._read_kea() == {}, "topology._read_kea: invalid -> {}")

    import assign_plan as P
    import fw_lint as L

    class Ctx:
        def __init__(self, files):
            self.files = files

        def read(self, p):
            return self.files.get(p, "")

    check(L.kea_reservations(Ctx({"/etc/kea/kea-dhcp4.conf": COMMENTED})) == {"192.168.100.50"},
          "fw_lint: commented-out reservation not counted")

    class Res:
        def __init__(self):
            self.files, self.warns, self.changes = {}, [], []

        def warn(self, m):
            self.warns.append(m)

        def change(self, kind, m):
            self.changes.append(m)

        def file(self, kind, p, old, new, mode):
            self.files[p] = {"old": old, "new": new}

    import ipaddress

    class M:
        def __init__(self, dev_old, dev_new):
            ip = ipaddress.ip_interface("192.168.100.1/24")
            self.old = {"lan": {"name": "LAN", "role": "lan", "device": dev_old, "ip": ip}}
            self.nw = {"lan": {"name": "LAN", "role": "lan", "device": dev_new, "ip": ip, "dhcp": True,
                               "pool": "192.168.100.100 - 192.168.100.200"}}
            self.added = []

        def net_ids(self):
            return list(self.nw)

    res = Res()
    P.r_kea(Ctx({P.T.KEA_CONF: COMMENTED}), M("eth1", "eth9"), res)
    check(not any("not valid JSON" in w for w in res.warns), "assign_plan: commented Kea config is parsed: %r" % (res.warns,))
    new = (res.files.get(P.T.KEA_CONF) or {}).get("new") or ""
    nd = K.loads(new) if new else {}
    check(new.startswith(head) and nd["Dhcp4"]["option-data"] == d4["option-data"]
          and nd["Dhcp4"]["interfaces-config"]["interfaces"] == ["eth9"]
          and nd["Dhcp4"]["subnet4"][0]["interface"] == "eth9",
          "assign_plan: device move rendered, header + strings kept")
    check(any("comments inside the JSON are not kept" in w for w in res.warns),
          "assign_plan: warns that body comments are dropped")
    res = Res()
    P.r_kea(Ctx({P.T.KEA_CONF: COMMENTED}), M("eth1", "eth1"), res)
    check(not res.files, "assign_plan: no change -> commented file not rewritten")
    res = Res()
    P.r_kea(Ctx({P.T.KEA_CONF: '{"Dhcp4": '}), M("eth1", "eth9"), res)
    check(any("not valid JSON" in w for w in res.warns) and not res.files, "assign_plan: invalid Kea JSON -> warning")

    # ------------------------------------------------------- installer decision
    fn = re.search(r"^kea_is_replaceable\(\) \{.*?^\}\n", src, re.M | re.S).group(0)

    def replaceable(text):
        p = os.path.join(TMP, "decide.conf")
        with open(p, "w") as f:
            f.write(text)
        body = fn.replace("/etc/kea/kea-dhcp4.conf", p)
        rc = subprocess.run(["bash", "-c", 'INSTALLER_MARK="%s"; KEA_EDIT_MARK="%s"\n%s\nkea_is_replaceable'
                             % (mark, emark, body)], timeout=10).returncode
        os.unlink(p)
        return rc == 0

    check(replaceable(gen), "installer: untouched generated config is replaceable")
    check(not replaceable(K.dumps(gd, K.split_header(gen)[0])), "installer: dashboard-edited config is kept")
    check(not replaceable('{"Dhcp4": {}}'), "installer: hand-written config is kept")
    check(replaceable(""), "installer: empty config is replaceable")
finally:
    shutil.rmtree(TMP, ignore_errors=True)

print("kea_conf_check: %d passed, %d failed" % (PASS, FAIL))
sys.exit(1 if FAIL else 0)
