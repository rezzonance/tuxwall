"""Read and write /etc/kea/kea-dhcp4.conf the way Kea itself accepts it.

Kea's config is JSON plus comments: '// ...' and '# ...' to the end of the
line and '/* ... */' blocks. The installer writes a '// Generated by ...'
header line, so strict json.load() fails on a fresh install. Comments are
removed only outside JSON strings, so URLs and hostnames containing '//' or
'#' stay intact. A rewrite keeps the leading comment header (comments inside
the JSON body cannot survive a parse/dump round trip).

Pure stdlib, no other TuxWall imports: used by api_server, topology and
assign_plan.
"""

import json
import os
import tempfile

KEA_CONF = "/etc/kea/kea-dhcp4.conf"
# tuxwall-install.sh replaces a Kea config carrying its own header mark on
# a re-run/upgrade unless the edit mark below is present too: a dashboard
# rewrite keeps the header and adds the edit mark once, so reservations and
# DHCP form changes survive the next installer run.
INSTALLER_MARK = "Generated by the TuxWall installer"
EDIT_MARK = "Edited from the TuxWall dashboard"
EDIT_LINE = "// %s: the installer keeps this file on re-runs/upgrades.\n" % EDIT_MARK


def _scan(text):
    """Yield (start, end, kind) spans; kind is 'code', 'str' or 'comment'."""
    i, n, start = 0, len(text), 0
    while i < n:
        c = text[i]
        if c == '"':
            if start < i:
                yield start, i, "code"
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            j = min(j + 1, n)
            yield i, j, "str"
            i = start = j
        elif c == "#" or text.startswith("//", i):
            if start < i:
                yield start, i, "code"
            j = text.find("\n", i)
            j = n if j < 0 else j
            yield i, j, "comment"
            i = start = j
        elif text.startswith("/*", i):
            if start < i:
                yield start, i, "code"
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            yield i, j, "comment"
            i = start = j
        else:
            i += 1
    if start < n:
        yield start, n, "code"


def strip_comments(text):
    """Text with every comment outside strings blanked; line numbers keep."""
    out = []
    for a, b, kind in _scan(text):
        seg = text[a:b]
        if kind == "comment":
            seg = "".join(ch if ch == "\n" else " " for ch in seg)
        out.append(seg)
    return "".join(out)


def has_comments(text):
    return any(kind == "comment" for _a, _b, kind in _scan(text))


def split_header(text):
    """(header, rest): the leading comments/blank lines before the JSON.

    The header is '' when there are no leading comments; otherwise it is the
    original text up to the line holding the first JSON character."""
    first = None
    for a, b, kind in _scan(text):
        if kind == "comment":
            continue
        seg = text[a:b]
        k = len(seg) - len(seg.lstrip())
        if k < len(seg):
            first = a + k
            break
    if first is None:
        first = len(text)
    head = text[:first]
    nl = head.rfind("\n")
    if nl >= 0 and not head[nl + 1:].strip():
        head = head[:nl + 1]
    if not has_comments(head):
        return "", text
    return head, text[len(head):]


def body_has_comments(text):
    """True when comments exist after the header (lost on a rewrite)."""
    return has_comments(split_header(text)[1])


def loads(text):
    """Parse Kea JSON with comments; ValueError when it is not valid."""
    try:
        return json.loads(text)
    except ValueError:
        pass
    return json.loads(strip_comments(text))


def read(path=KEA_CONF):
    with open(path) as f:
        return loads(f.read())


def rewrite_header(header):
    """The header for a rewritten file: the original lines, plus the edit
    mark (once) when the installer generated the file."""
    if not header:
        return ""
    if not header.endswith("\n"):
        header += "\n"
    if INSTALLER_MARK in header and EDIT_MARK not in header:
        header += EDIT_LINE
    return header


def dumps(data, header=""):
    """Kea config text for a rewrite: the original comment header, then
    indented JSON."""
    return rewrite_header(header) + json.dumps(data, indent=4) + "\n"


def read_header(path=KEA_CONF):
    try:
        with open(path) as f:
            return split_header(f.read())[0]
    except (OSError, UnicodeDecodeError):
        return ""


def write(path, data, header=None):
    """Atomic rewrite keeping owner, mode and the leading comment header
    (read from the current file unless given)."""
    if header is None:
        header = read_header(path)
    text = dumps(data, header)
    if loads(text) != data:
        raise ValueError("Kea config round trip mismatch; not written")
    try:
        st = os.stat(path)
        mode, uid, gid = st.st_mode & 0o7777, st.st_uid, st.st_gid
    except FileNotFoundError:
        mode, uid, gid = 0o644, None, None
    d = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(prefix="." + os.path.basename(path) + ".", suffix=".tmp", dir=d)
    try:
        os.fchmod(fd, mode)
        if uid is not None and (uid, gid) != (os.geteuid(), os.getegid()):
            os.fchown(fd, uid, gid)
        with os.fdopen(fd, "w") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
