    echo "# LAN = $LAN ($NET_GW/$NET_PREFIX), WAN = $WAN ($WAN_MODE)."
    echo "network:"
    echo "  version: 2"
    echo "  ethernets:"
    echo "    $LAN:"
    echo "      dhcp4: false"
    echo "      dhcp6: false"
    echo "      accept-ra: false"
