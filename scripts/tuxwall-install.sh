step_services() {
    q systemctl daemon-reload
    local svc
    local -a base=(nginx tuxwall tuxwall-nat avahi-daemon tuxwall-blocklist-update.timer suricata-update.timer)
    [[ $ROLE == gateway ]] && base=(unbound "${base[@]}")
    for svc in "${base[@]}"; do
        q systemctl enable "$svc" || true
        q systemctl restart "$svc" || warn "$svc did not start (systemctl status $svc)"
    done
    if [[ $ROLE == gateway ]]; then
        for svc in kea-dhcp4-server radvd tuxwall-kea-mirror.timer; do
            q systemctl enable "$svc" || true
            if [[ $NET_APPLY_DECISION == now ]]; then
                q systemctl restart "$svc" || warn "$svc did not start (systemctl status $svc)"
            fi
        done
    fi
    q systemctl enable suricata || true
    q systemctl restart suricata || info "Suricata is not running yet (it starts once rules are downloaded)"
    if command -v cscli >/dev/null 2>&1; then
        for svc in crowdsec crowdsec-firewall-bouncer crowdsec-dedupe.timer; do
            q systemctl enable "$svc" 2>/dev/null || true
            q systemctl restart "$svc" 2>/dev/null || true
        done
    fi
    ok "Services enabled and started"

    if wait_api 30; then
        ok "Dashboard API is up"
        local tok=/etc/tuxwall/internal-token hdr
        if [[ -s $tok ]]; then
            hdr="$(mktemp)"; chmod 600 "$hdr"
            printf 'X-Tuxwall-Token: %s\n' "$(cat "$tok")" >"$hdr"
            if curl -fsS -m 15 -X POST -H @"$hdr" http://127.0.0.1:8008/api/blocklists/update >>"$LOG" 2>&1; then
                ok "First blocklist download started (Blocklists page shows progress)"
            else
                warn "Could not start the first blocklist download; the daily timer will do it."
            fi
            rm -f "$hdr"
        else
            info "Blocklists download on the daily timer (no internal token yet)"
        fi
    else
        warn "Dashboard API did not answer within 30s (journalctl -u tuxwall)"
    fi
}

check() {   # check LEVEL "label" cmd...   LEVEL: critical | normal | pending
    local level=$1 label=$2; shift 2
    if "$@" >>"$LOG" 2>&1; then
        printf '    %s✓%s %s\n' "$C_G" "$C_0" "$label"
    elif [[ $level == pending ]]; then
        printf '    %s…%s %s %s(after reboot)%s\n' "$C_Y" "$C_0" "$label" "$C_DIM" "$C_0"
    elif [[ $level == critical ]]; then
        printf '    %s✗%s %s\n' "$C_R" "$C_0" "$label"
        CRIT_FAIL=$((CRIT_FAIL + 1))
        log "CHECK FAILED (critical): $label"
    else
        printf '    %s!%s %s\n' "$C_Y" "$C_0" "$label"
        log "CHECK FAILED: $label"
    fi
}
active()       { systemctl is-active --quiet "$1"; }
http_ok()      { curl -fsS -m 5 -o /dev/null "$1"; }
ufw_active()   { ufw status | grep -q '^Status: active'; }
nat_ok()       { iptables -t nat -S POSTROUTING | grep -q -- "-o $WAN -j MASQUERADE"; }
fwd_ok()       { [[ "$(sysctl -n net.ipv4.ip_forward 2>/dev/null || true)" == 1 ]]; }
dns_ok()       { getent hosts archive.ubuntu.com >/dev/null; }
lan_ip_ok()    { ip -4 -o addr show dev "$LAN" | grep -q " $NET_GW/"; }

step_verify() {
    local pend=normal
    [[ ${NET_APPLY_DECISION:-now} == reboot ]] && pend=pending
    check critical "Dashboard web server (nginx)"     http_ok http://127.0.0.1/
    check critical "Dashboard API"                    http_ok http://127.0.0.1/api/auth/session
    check critical "Firewall active (UFW)"            ufw_active
    if [[ $ROLE == gateway ]]; then
        check critical "Packet forwarding"            fwd_ok
        check critical "NAT masquerade on $WAN"       nat_ok
        check critical "DNS resolver (Unbound)"       active unbound
        check normal   "Name resolution"              dns_ok
        check "$pend"  "LAN address $NET_GW on $LAN"  lan_ip_ok
        check "$pend"  "DHCP server (Kea)"            active kea-dhcp4-server
        check "$pend"  "IPv6 router adverts (radvd)"  active radvd
    fi
    check normal "Intrusion detection (Suricata)"     active suricata
    command -v cscli >/dev/null 2>&1 && check normal "CrowdSec" active crowdsec
    (( WITH_AGENT )) && check normal "AI assistant (tuxwall-agent)" active tuxwall-agent
    check normal "mDNS reflector (Avahi)"             active avahi-daemon
    return 0
}

###############################################################################
#  Console (first-boot) mode
###############################################################################
stage_console() {
    have_repo || die "--console needs the TuxWall source tree next to this script."
    printf '\n  %sConsole setup%s\n' "$C_BOLD" "$C_0"
    hr
    mkdir -p "$APPLIANCE_DIR" /etc/tuxwall
    q rsync -a --delete --exclude '.git' --exclude '__pycache__' --exclude '*.pyc' \
        --exclude '*.bak' --exclude '*.bak-*' --exclude '*.bak.*' "$REPO_DIR/" "$APPLIANCE_DIR/src/"
    chmod 755 "$APPLIANCE_DIR/src/tuxwall-install.sh"
    chown -R root:root "$APPLIANCE_DIR"
    chmod -R go-w "$APPLIANCE_DIR"
    ok "Installer staged in $APPLIANCE_DIR/src"

    local serial unit dropdir
    serial="$(sed -n 's/.*console=\(ttyS[0-9]*\).*/\1/p' /proc/cmdline 2>/dev/null)"
    if [[ -n $serial ]]; then
        unit="serial-getty@$serial.service"
        dropdir="/etc/systemd/system/$unit.d"
        mkdir -p "$dropdir"
        printf '# TuxWall one-time console setup (removed when it starts)\n[Service]\nExecStart=\nExecStart=-/sbin/agetty --autologin root --keep-baud 115200,57600,38400,9600 %%I $TERM\n' \
            >"$dropdir/tuxwall-console-setup.conf"
    else
        unit="getty@tty1.service"
        dropdir="/etc/systemd/system/$unit.d"
        mkdir -p "$dropdir"
        printf '# TuxWall one-time console setup (removed when it starts)\n[Service]\nExecStart=\nExecStart=-/sbin/agetty --autologin root --noclear %%I $TERM\n' \
            >"$dropdir/tuxwall-console-setup.conf"
    fi
    q systemctl daemon-reload

    cat >"$CONSOLE_HOOK" <<'HOOK'
# TuxWall one-time console setup, installed by tuxwall-install.sh --console.
# The installer removes this file (and the autologin) as soon as it starts.
if [ -f /etc/tuxwall/.console-setup-pending ] && [ "$(id -u)" = 0 ] \
   && [ -x /opt/tuxwall-appliance/src/tuxwall-install.sh ]; then
    _tw_console="$(sed -n 's/.*console=\(ttyS[0-9]*\).*/\1/p' /proc/cmdline 2>/dev/null)"
    [ -n "$_tw_console" ] || _tw_console=tty1
    if [ "$(tty 2>/dev/null)" = "/dev/$_tw_console" ]; then
        exec /opt/tuxwall-appliance/src/tuxwall-install.sh --from-console
    fi
    unset _tw_console
fi
HOOK
    chmod 644 "$CONSOLE_HOOK"
    touch "$PENDING"
    ok "One-time autologin armed on ${serial:-tty1} ($unit)"

    if (( DISABLE_MULTIPATH )) && command -v multipathd >/dev/null 2>&1; then
        backup_file /etc/multipath.conf
        mkdir -p /etc/multipath
        printf 'defaults {\n    user_friendly_names no\n}\n' >/etc/multipath.conf
        touch /etc/multipath/bindings
        printf 'blacklist dm_multipath\n' >/etc/modprobe.d/blacklist-multipath.conf
        q systemctl disable --now multipathd.service || true
        ok "multipathd will not claim the system disk"
    fi
    hr
    printf '\n  Reboot (or log in on %s as root). The guided install starts there once;\n' "${serial:-tty1}"
    printf '  the autologin is removed the moment it starts, whatever the outcome.\n'
    printf '  Cancel instead:  sudo rm %s %s %s/tuxwall-console-setup.conf\n\n' "$PENDING" "$CONSOLE_HOOK" "$dropdir"
}

console_disarm() {
    rm -f "$PENDING" "$CONSOLE_HOOK"
    rm -f /etc/systemd/system/getty@tty1.service.d/tuxwall-console-setup.conf \
          /etc/systemd/system/serial-getty@*.service.d/tuxwall-console-setup.conf 2>/dev/null || true
    systemctl daemon-reload >/dev/null 2>&1 || true
    log "console autologin disarmed"
}

###############################################################################
#  Main
###############################################################################
final_summary() {
    local url="http://${NET_GW:-$(hostname -I 2>/dev/null | awk '{print $1}' || true)}/"
    printf '\n'
    hr
    if (( CRIT_FAIL )); then
        printf '  %s%sTuxWall installed with %d problem(s) to fix%s\n' "$C_BOLD" "$C_Y" "$CRIT_FAIL" "$C_0"
    else
        printf '  %s%sTuxWall %s is installed%s\n' "$C_BOLD" "$C_G" "$PKG_VERSION" "$C_0"
    fi
    hr
    kv "Dashboard"  "$url"
    kv "First login" "open the dashboard and create the first administrator"
    [[ $ROLE == gateway ]] && kv "Gateway name" "gateway.$DOMAIN"
    kv "Log"        "$LOG"
    [[ -d $BACKUP_DIR ]] && kv "Backups" "$BACKUP_DIR"
    if [[ ${NET_APPLY_DECISION:-} == reboot ]]; then
        printf '\n  %s%sReboot to activate the LAN:%s sudo reboot\n' "$C_BOLD" "$C_Y" "$C_0"
        printf '  %sThen connect a device to %s and open %s%s\n' "$C_DIM" "$LAN" "$url" "$C_0"
    fi
    if (( ${#WARNINGS[@]} )); then
        printf '\n  %sWarnings (%d)%s\n' "$C_Y" "${#WARNINGS[@]}" "$C_0"
        local w
        for w in "${WARNINGS[@]}"; do printf '    %s!%s %s\n' "$C_Y" "$C_0" "$w"; done
    fi
    printf '\n'
}

main() {
    ORIG_ARGS="$*"
    parse_args "$@"
    require_root
    init_log
    acquire_lock
    (( FROM_CONSOLE )) && console_disarm
    banner
    if (( CONSOLE_STAGE )); then
        stage_console
        exit 0
    fi

    preflight
    if (( ! INTERACTIVE )) && (( ! ASSUME_YES )) && (( ! DRY_RUN )); then
        die "No terminal for questions: re-run with --yes and the options you need (see --help)."
    fi
    gather_config
    review
    build_steps

    if (( DRY_RUN )); then
        printf '\n  %sPlan%s %s(dry run: nothing was changed)%s\n' "$C_BOLD" "$C_0" "$C_DIM" "$C_0"
        local i=1 s
        for s in "${STEPS[@]}"; do printf '    %2d. %s\n' "$i" "${s#*|}"; i=$((i + 1)); done
        printf '\n'
        exit 0
    fi

    if (( INTERACTIVE )); then
        confirm "Install TuxWall with these settings?" y || user_abort
    fi
    log "settings: source=$SOURCE role=$ROLE wan=$WAN/$WAN_MODE lan=$LAN net=$NET_CIDR gw=$NET_GW domain=$DOMAIN ula=$ULA kea=$KEA_ACTION radvd=$RADVD_ACTION unbound=$UNBOUND_ACTION apply=$NET_APPLY_DECISION crowdsec=$WITH_CROWDSEC agent=$WITH_AGENT"

    local s
    for s in "${STEPS[@]}"; do
        step "${s#*|}"
        "${s%%|*}"
    done

    if (( CRIT_FAIL == 0 )); then
        touch "$MARKER"
    fi
    final_summary
    if (( FROM_CONSOLE )); then
        local _; ask _ "  Press Enter to finish (a normal login prompt follows)."
    fi
    if (( CRIT_FAIL )); then exit 1; fi
    exit 0
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    main "$@"
fi
