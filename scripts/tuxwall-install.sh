init_log() {
    touch "$LOG"; chmod 600 "$LOG"
    {
        printf '\n'
        printf '=%.0s' {1..72}; printf '\n'
        printf '%s  tuxwall-install.sh %s  args: %s\n' "$(date '+%F %T')" "$INSTALLER_VERSION" "${ORIG_ARGS:-}"
