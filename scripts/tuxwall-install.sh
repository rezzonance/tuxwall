    log "===== [$STEP_N/$STEP_TOTAL] $*"
}

# Run a command with its output going to the log only.
q() { "$@" >>"$LOG" 2>&1; }

# Run a long command with a spinner and elapsed time; output goes to the log.
run_long() {
    local msg="$1"; shift
    log "RUN  $*"
    if [[ ! -t 1 ]]; then
        "$@" >>"$LOG" 2>&1
        return
    fi
    ( trap - ERR; "$@" ) >>"$LOG" 2>&1 &
    # shellcheck disable=SC1003
    local pid=$! i=0 rc=0 start=$SECONDS frames='|/-\'
    [[ "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" =~ [Uu][Tt][Ff]-?8 ]] && frames='⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏'
    while kill -0 "$pid" 2>/dev/null; do
        printf '\r  %s%s%s %s %s(%ss)%s' "$C_C" "${frames:i%${#frames}:1}" "$C_0" "$msg" "$C_DIM" "$((SECONDS - start))" "$C_0"
        i=$((i + 1))
        sleep 0.15
    done
    wait "$pid" || rc=$?
    printf '\r\033[K'
    return "$rc"
}

on_err() {
    local rc=$? line=$1 cmd=$2
    trap - ERR
    log "ERROR rc=$rc line=$line cmd=$cmd"
    die "Step failed (line $line, exit $rc): $cmd"
}
trap 'on_err $LINENO "$BASH_COMMAND"' ERR

ask() {   # ask VAR "prompt"
    local __v=$1 __p=$2 __a=""
    read -r -p "$__p " __a </dev/tty || __a=""
    printf -v "$__v" '%s' "$__a"
}

confirm() {   # confirm "question" default(y|n)
    local q=$1 def=${2:-n} a
    if (( ! INTERACTIVE )); then [[ $def == y ]]; return; fi
    local hint="[y/N]"; [[ $def == y ]] && hint="[Y/n]"
    ask a "  $q $hint"
    a=${a:-$def}
    [[ $a =~ ^[yY] ]]
}

user_abort() { printf '\n  %sInstallation cancelled. Nothing was changed.%s\n\n' "$C_DIM" "$C_0"; exit 0; }

menu() {   # menu VAR "title" default "label|description" ...
    local __var=$1 title=$2 def=$3; shift 3
    local n=$# i=1 o label desc mark ans
    printf '\n  %s%s%s\n' "$C_BOLD" "$title" "$C_0"
    for o in "$@"; do
        label=${o%%|*}; desc=${o#*|}
        mark=" "; [[ $i == "$def" ]] && mark="${C_G}›${C_0}"
        printf '  %s %s%d)%s %-28s %s%s%s\n' "$mark" "$C_C" "$i" "$C_0" "$label" "$C_DIM" "$desc" "$C_0"
        i=$((i + 1))
    done
    while true; do
        ask ans "    Choose 1-$n (Enter = $def, q = quit):"
        ans=${ans:-$def}
        [[ $ans =~ ^[qQ]$ ]] && user_abort
        if [[ $ans =~ ^[0-9]+$ ]] && (( ans >= 1 && ans <= n )); then
            printf -v "$__var" '%s' "$ans"
            return 0
        fi
        printf '    %sEnter a number between 1 and %d.%s\n' "$C_Y" "$n" "$C_0"
    done
}

