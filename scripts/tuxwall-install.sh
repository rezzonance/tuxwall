write_netplan() {
    local f=/etc/netplan/90-tuxwall.yaml tmp other
    tmp="$(mktemp)"
    netplan_yaml >"$tmp"
    backup_file "$f"
    install -m 600 "$tmp" "$f"
    rm -f "$tmp"
    if ! q netplan generate; then
        rm -f "$f"
        [[ -e "$BACKUP_DIR$f" ]] && cp -a "$BACKUP_DIR$f" "$f"
        die "netplan rejected the generated config (details in $LOG)."
    fi
    ok "Netplan: $LAN = $NET_GW/$NET_PREFIX + $ULA::1/64$([[ $WAN_MODE == dhcp ]] && echo ", $WAN = DHCP")"
    other="$(grep -l -E "^[[:space:]]+$LAN:" /etc/netplan/*.yaml 2>/dev/null | grep -v 90-tuxwall.yaml || true)"
    [[ -n $other ]] && note "Also mentions $LAN: $other (TuxWall's file overrides its DHCP setting)"
    return 0
}

