#!/usr/bin/env bash
###############################################################################
#  TuxWall unified installer
#  ---------------------------------------------------------------------------
#  One script for every way of installing TuxWall. It replaces setup.sh,
#  install.sh + stage.sh (first-boot wizard), install-repo.sh and the manual
#  .deb steps.
#
#    sudo bash tuxwall-install.sh               guided install (recommended)
#    sudo bash tuxwall-install.sh --dry-run     show the plan, change nothing
#    sudo bash tuxwall-install.sh --console     run the guided install on the
#                                               next console login (headless /
#                                               fresh appliance installs)
#    sudo bash tuxwall-install.sh --help        every option
#
#  Install sources:
#    local  build a package from this folder and install it (test your changes)
#    apt    the signed TuxWall APT repository (latest release)
#    deb    a tuxwall_*.deb file you already have
#
#  Roles:
#    gateway    TuxWall routes the network: WAN/LAN, DHCP, DNS, IPv6 RA, NAT
#    dashboard  install TuxWall but leave this machine's network config alone
#
#  Every path goes through the same .deb (maintainer scripts included), so a
#  source install and an APT install end up identical. Safe to re-run.
#  Full log: /var/log/tuxwall-install.log
###############################################################################
