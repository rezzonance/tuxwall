step_harden() {
    local w=/var/www/html f
    find "$w" \( -name '*.bak-[0-9]*' -o -name '*.bak.[0-9]*' -o -name '*.pyc' \) -type f -delete 2>/dev/null || true
    find "$w" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true

    if (( AGENT_EDIT_WEBROOT )); then
        warn "Web root left writable by tuxwall-agent (--agent-edit-webroot)."
    else
        chown -R root:root "$w"
        find "$w" -type d -exec chmod 755 {} +
        find "$w" -type f -exec chmod 644 {} +
        chmod 755 "$w/includes/api_server.py"
        find "$w/scripts" -maxdepth 1 -name '*.sh' -type f -exec chmod 755 {} + 2>/dev/null || true
        ok "Dashboard code is root-owned; nginx and the agent can read but not change it"
    fi

    for f in /etc/tuxwall/llm.json /etc/tuxwall/auth.json /etc/tuxwall/internal-token \
             /etc/tuxwall/agent-token /etc/tuxwall/reporting.json /etc/tuxwall/llm.json.bak*; do
        if [[ -e $f ]]; then chmod 600 "$f"; fi
    done
    ok "Secrets in /etc/tuxwall readable by root only"
}

