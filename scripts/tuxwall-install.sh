acquire_lock() {
    exec 9>"$LOCK"
    flock -n 9 || die "Another TuxWall installer is already running."
}

preflight() {
    command -v apt-get >/dev/null 2>&1 || die "apt-get not found: TuxWall needs Ubuntu (or Debian)."
    command -v systemctl >/dev/null 2>&1 || die "systemd is required."
    command -v python3 >/dev/null 2>&1 || die "python3 is required (it ships with Ubuntu Server)."

    local id="" ver=""
    if [[ -r /etc/os-release ]]; then
        id="$(. /etc/os-release; echo "${ID:-}")"
        ver="$(. /etc/os-release; echo "${VERSION_ID:-}")"
    fi
    if [[ $id != ubuntu ]]; then
        warn "This is ${id:-an unknown OS}; TuxWall is tested on Ubuntu 24.04 and newer."
    elif [[ ${ver%%.*} -lt 24 ]]; then
        warn "Ubuntu $ver detected; TuxWall needs 24.04 or newer."
    fi

    detect_phys_ifaces
    detect_ssh
    detect_ssh_ports
    (( ${#PHYS_IFACES[@]} )) || warn "No physical network interfaces detected."

    if [[ -t 0 || -r /dev/tty ]] && (( ! ASSUME_YES )) && { : </dev/tty; } 2>/dev/null; then
        INTERACTIVE=1
    fi
}

