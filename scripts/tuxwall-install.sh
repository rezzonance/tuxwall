    local-data-ptr: "$ULA::1 gateway.$DOMAIN."
UNB
}

write_unbound() {
    local d=/etc/unbound/unbound.conf.d written=()
    mkdir -p "$d" /var/lib/unbound

    if [[ $UNBOUND_ACTION != keep ]]; then
        backup_file "$d/router-dns.conf"
        unbound_router_conf >"$d/router-dns.conf"
        written+=("$d/router-dns.conf")
    elif ! grep -qs "access-control:.*${NET_CIDR%/*}" "$d"/*.conf; then
        warn "Your Unbound config has no access-control for $NET_CIDR: LAN clients may be refused."
    fi

    # Gateway name in its own file: the Local Domains page owns 98-local-domains.conf.
    backup_file "$d/97-tuxwall-gateway.conf"
    unbound_gateway_conf >"$d/97-tuxwall-gateway.conf"
    written+=("$d/97-tuxwall-gateway.conf")

    # Pre-empt the packaged default (hard-coded 192.168.1.1 / home.arpa) with
    # the include the Local Domains page writes itself.
    if [[ ! -s $d/98-local-domains.conf ]] || grep -q 'gateway.home.arpa. IN A 192.168.1.1' "$d/98-local-domains.conf"; then
        backup_file "$d/98-local-domains.conf"
        [[ -s /var/lib/unbound/local-domains.conf ]] || \
            printf '# Generated by the tuxwall Local Domains page - DO NOT EDIT\n# 0 local domains\nserver:\n' >/var/lib/unbound/local-domains.conf
        printf '# Managed by the tuxwall Local Domains page - DO NOT EDIT\nserver:\ninclude: "/var/lib/unbound/local-domains.conf"\n' >"$d/98-local-domains.conf"
        written+=("$d/98-local-domains.conf")
    fi

    # DNSSEC trust anchor (unbound refuses to start without it).
    if [[ ! -s /var/lib/unbound/root.key ]]; then
        if [[ -s /usr/share/dns/root.key ]]; then
            cp /usr/share/dns/root.key /var/lib/unbound/root.key
        else
            q unbound-anchor -a /var/lib/unbound/root.key || true
        fi
        chown unbound:unbound /var/lib/unbound/root.key 2>/dev/null || true
    fi

    if ! q unbound-checkconf; then
        local f
        for f in "${written[@]}"; do
            if [[ -e "$BACKUP_DIR$f" ]]; then cp -a "$BACKUP_DIR$f" "$f"; else rm -f "$f"; fi
        done
        warn "unbound-checkconf rejected the new files; restored the previous Unbound config."
        return 0
    fi
    ok "Unbound: serves $NET_CIDR + $ULA::/48, gateway.$DOMAIN → $NET_GW"
}

step_gateway_config() {
    mkdir -p /etc/tuxwall "$BACKUP_DIR"

    # Packet forwarding, persisted where the package expects it.
    printf '# %s\nnet.ipv4.ip_forward=1\nnet.ipv6.conf.all.forwarding=1\n' "$INSTALLER_MARK" \
        >/etc/sysctl.d/99-tuxwall-router.conf
    q sysctl -w net.ipv4.ip_forward=1
    q sysctl -w net.ipv6.conf.all.forwarding=1
    ok "IPv4/IPv6 forwarding enabled"

    write_netplan
    if [[ $KEA_ACTION == keep ]]; then info "Kea: keeping your existing config"; else write_kea; fi
    if [[ $RADVD_ACTION == keep ]]; then info "radvd: keeping your existing config"; else write_radvd; fi
    write_unbound

    # NAT follows the chosen WAN even before a default route exists at boot.
    mkdir -p /etc/systemd/system/tuxwall-nat.service.d
    printf '[Service]\nEnvironment=TUXWALL_WAN_IFACE=%s\n' "$WAN" \
        >/etc/systemd/system/tuxwall-nat.service.d/10-wan.conf
    ok "NAT pinned to WAN interface $WAN"
}

step_dns() {
    q systemctl disable --now systemd-resolved.service || true
    q systemctl disable --now systemd-resolved-varlink.socket systemd-resolved-monitor.socket || true
    if [[ -e /etc/resolv.conf || -L /etc/resolv.conf ]]; then
        mkdir -p "$BACKUP_DIR/etc"
        cp -aL /etc/resolv.conf "$BACKUP_DIR/etc/resolv.conf" 2>/dev/null || true
    fi
    rm -f /etc/resolv.conf
    printf '# %s: this gateway resolves through its own Unbound.\nnameserver 127.0.0.1\nnameserver ::1\nsearch %s\n' \
        "$INSTALLER_MARK" "$DOMAIN" >/etc/resolv.conf
    q systemctl enable unbound || true
    q systemctl restart unbound || true
    if wait_dns 20; then
        ok "systemd-resolved retired; this gateway now resolves through Unbound"
    else
        printf '# %s: temporary public resolvers (Unbound did not answer).\nnameserver 1.1.1.1\nnameserver 9.9.9.9\nsearch %s\n' \
            "$INSTALLER_MARK" "$DOMAIN" >/etc/resolv.conf
        warn "Unbound did not answer; /etc/resolv.conf uses 1.1.1.1 / 9.9.9.9 for now. Switch it back to 127.0.0.1 once Unbound works."
    fi
}

build_local_deb() {
    local stage ver
    stage="$(mktemp -d /tmp/tuxwall-build.XXXXXX)"
    chmod 755 "$stage"   # apt's _apt user must be able to read the .deb
    ver="$(repo_version)+src$(date +%Y%m%d%H%M)"
    local excl=(--exclude '*.bak' --exclude '*.bak-*' --exclude '*.bak.*' --exclude '__pycache__'
                --exclude '*.pyc' --exclude '*.orig' --exclude '*.swp' --exclude '*~' --exclude '.git')
    rsync -a "${excl[@]}" "$REPO_DIR/pkg/" "$stage/pkg/"
    mkdir -p "$stage/pkg/var/www/html"
    rsync -a "${excl[@]}" "$REPO_DIR/www/" "$stage/pkg/var/www/html/"
    # Ship the SQM helper in the package (the plain .deb never had it).
    if [[ -f $REPO_DIR/scripts/tuxwall-sqm.sh ]]; then
        install -D -m 755 "$REPO_DIR/scripts/tuxwall-sqm.sh" "$stage/pkg/usr/local/sbin/tuxwall-sqm.sh"
    fi
    # The vhost hard-codes 192.168.1.1 / 10.0.0.1 / fd00:1::1 listeners, which
    # stop nginx from starting on any box without exactly those addresses.
    # [::] (all IPv6 addresses) has no hex digit, so it is kept.
    sed -i -E '/^[[:space:]]*listen[[:space:]]+(([0-9]{1,3}\.){3}[0-9]{1,3}|\[[0-9a-fA-F:]*[0-9a-fA-F][0-9a-fA-F:]*\]):[0-9]+/d' \
        "$stage/pkg/etc/nginx/sites-available/tuxwall"
    sed -i "s/^Version: .*/Version: $ver/" "$stage/pkg/DEBIAN/control"
    find "$stage/pkg" -type d -exec chmod 755 {} +
    chmod -R go-w "$stage/pkg"
    chmod 755 "$stage/pkg/DEBIAN"/{postinst,prerm,postrm} 2>/dev/null || true
    chmod 644 "$stage/pkg/DEBIAN"/{control,conffiles} 2>/dev/null || true
    find "$stage/pkg/usr/local/sbin" -type f -exec chmod 755 {} + 2>/dev/null || true
    chmod 755 "$stage/pkg/var/www/html/includes/api_server.py"
    q dpkg-deb --root-owner-group -Zxz --build "$stage/pkg" "$stage/tuxwall_${ver}_all.deb" \
        || die "dpkg-deb could not build the package."
    DEB_FILE="$stage/tuxwall_${ver}_all.deb"
    PKG_VERSION=$ver
    ok "Built tuxwall $ver from $REPO_DIR"
}

register_apt_repo() {
    local tmp fpr
    tmp="$(mktemp -d)"
    mkdir -m 700 "$tmp/gnupg"
    if [[ -s $REPO_DIR/apt-public.asc ]]; then
        cp "$REPO_DIR/apt-public.asc" "$tmp/key.asc"
    elif ! curl -fsSL --retry 3 -m 60 "$APT_REPO_URL/public.asc" -o "$tmp/key.asc" 2>>"$LOG"; then
        rm -rf "$tmp"; return 1
    fi
    GNUPGHOME="$tmp/gnupg" gpg --batch --yes --dearmor -o "$tmp/tuxwall.gpg" "$tmp/key.asc" 2>>"$LOG" || { rm -rf "$tmp"; return 1; }
    fpr="$(GNUPGHOME="$tmp/gnupg" gpg --batch --show-keys --with-colons "$tmp/tuxwall.gpg" 2>/dev/null | awk -F: '/^fpr:/{print $10; exit}' || true)"
    if [[ $fpr != "$APT_KEY_FPR" ]]; then
        rm -rf "$tmp"
        warn "TuxWall signing key fingerprint mismatch (got ${fpr:-none}); repository NOT added."
        return 1
    fi
    install -m 644 "$tmp/tuxwall.gpg" "$APT_KEYRING"
    echo "deb [signed-by=$APT_KEYRING] $APT_REPO_URL stable main" >"$APT_LIST"
    rm -rf "$tmp"
    return 0
}

step_package() {
    # Ubuntu's stock nginx site also serves /var/www/html, which makes the
    # package think a custom site exists and skip enabling the dashboard.
    if [[ -L /etc/nginx/sites-enabled/default && "$(readlink -f /etc/nginx/sites-enabled/default)" == /etc/nginx/sites-available/default ]]; then
        rm -f /etc/nginx/sites-enabled/default
        info "Disabled nginx's stock default site"
    fi
    # The package's postinst installs files owned by this user, so it must exist first.
    if ! id tuxwall-agent >/dev/null 2>&1; then
        q useradd --create-home --shell /bin/bash tuxwall-agent
        info "Created the tuxwall-agent user"
    fi

    case "$SOURCE" in
        local) build_local_deb ;;
        deb)   PKG_VERSION="$(dpkg-deb -f "$DEB_FILE" Version 2>/dev/null || true)" ;;
        apt)
            register_apt_repo || die "Could not add the TuxWall APT repository (see $LOG)."
            run_long "Refreshing package lists" apt-get update -q || die "apt-get update failed."
            ok "TuxWall APT repository added (key ${APT_KEY_FPR: -16} verified)" ;;
    esac

    local target=tuxwall
    [[ $SOURCE != apt ]] && target="$DEB_FILE"
    if ! run_long "Installing the TuxWall package" apt-get install "${APT_OPTS[@]}" "$target"; then
        die "Package installation failed. Fix the error above, then run: sudo dpkg --configure -a"
    fi
    PKG_VERSION="$(dpkg-query -W -f='${Version}' tuxwall 2>/dev/null || echo "$PKG_VERSION")"
    ok "tuxwall $PKG_VERSION installed"
    [[ $SOURCE == local ]] && rm -rf "$(dirname "$DEB_FILE")"
    return 0
}

step_post() {
    mkdir -p /etc/tuxwall /var/lib/tuxwall/backups/system
    chmod 755 /etc/tuxwall

    if have_repo; then
        [[ -f /etc/tuxwall/ui.json ]] || install -m 644 "$REPO_DIR/config/ui.json" /etc/tuxwall/ui.json
        [[ -f /etc/tuxwall/custom-blocklist.txt ]] || install -m 644 "$REPO_DIR/config/custom-blocklist.txt" /etc/tuxwall/custom-blocklist.txt
        [[ -f /etc/tuxwall/llm.json ]] || install -m 600 "$REPO_DIR/config/llm.json.example" /etc/tuxwall/llm.json
        if [[ ! -x /usr/local/sbin/tuxwall-sqm.sh && -f $REPO_DIR/scripts/tuxwall-sqm.sh ]]; then
            install -m 755 "$REPO_DIR/scripts/tuxwall-sqm.sh" /usr/local/sbin/tuxwall-sqm.sh
        fi
    elif [[ ! -f /etc/tuxwall/llm.json && -f /etc/tuxwall/llm.json.example ]]; then
        install -m 600 /etc/tuxwall/llm.json.example /etc/tuxwall/llm.json
    fi
    ok "Dashboard settings in /etc/tuxwall"

    local sqm_wan="${WAN:-$DEF_IF}"
    if [[ ! -f /etc/tuxwall/sqm.conf && -n $sqm_wan ]]; then
        printf '%s\n' '# TuxWall SQM rates (Mbit). Managed by System > Traffic Shaping.' \
            "WAN=$sqm_wan" 'UP_RATE=95mbit' 'DOWN_RATE=920mbit' >/etc/tuxwall/sqm.conf
        info "Traffic shaping seeded for $sqm_wan (off until enabled in System → Traffic Shaping)"
    fi

    # nginx: drop listeners for addresses this box does not have.
    local vhost=/etc/nginx/sites-available/tuxwall addr line
    if [[ -f $vhost ]]; then
        while read -r line; do
            addr="$(sed -E 's/^[[:space:]]*listen[[:space:]]+\[?([0-9a-fA-F:.]+)\]?:[0-9]+.*/\1/' <<<"$line")"
            if ! ip -o addr show 2>/dev/null | awk '{split($4,a,"/"); print a[1]}' | grep -qxF "$addr"; then
                backup_file "$vhost"
                sed -i "\|^[[:space:]]*listen[[:space:]]\+\[\?${addr//./\\.}\]\?:|d" "$vhost"
                info "nginx: removed listener for $addr (not on this machine)"
            fi
        done < <(grep -E '^[[:space:]]*listen[[:space:]]+(([0-9]{1,3}\.){3}[0-9]{1,3}|\[[0-9a-fA-F:]*[0-9a-fA-F][0-9a-fA-F:]*\]):' "$vhost" || true)
        ln -sf "$vhost" /etc/nginx/sites-enabled/tuxwall
        if q nginx -t; then ok "nginx dashboard site enabled"; else warn "nginx -t failed: check $vhost"; fi
    fi

    # Canary egress containment (only when OpenCanary is deployed).
    if id opencanary >/dev/null 2>&1 && ! grep -q "Tuxwall canary egress" /etc/ufw/before.rules 2>/dev/null; then
        python3 - <<'PYCANARY' && q ufw reload && ok "Canary egress containment applied"
def insert(path, anchor, lines):
    s = open(path).read()
    if "Tuxwall canary egress" in s or s.count(anchor) != 1:
        return
    open(path, "w").write(s.replace(anchor, "\n".join(lines) + "\n" + anchor))
insert("/etc/ufw/before.rules", "-A ufw-before-output -o lo -j ACCEPT", [
    "# --- Tuxwall canary (opencanary) egress containment ---",
    "-A ufw-before-output -m owner --uid-owner opencanary -p tcp -d 127.0.0.1 --dport 8008 -j ACCEPT",
    "-A ufw-before-output -m owner --uid-owner opencanary -p udp -d 127.0.0.1 --dport 53 -j ACCEPT",
    "-A ufw-before-output -m owner --uid-owner opencanary -p tcp -d 127.0.0.1 --dport 53 -j ACCEPT",
    "-A ufw-before-output -m owner --uid-owner opencanary -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT",
    "-A ufw-before-output -m owner --uid-owner opencanary -j REJECT",
])
insert("/etc/ufw/before6.rules", "-A ufw6-before-output -o lo -j ACCEPT", [
    "# --- Tuxwall canary (opencanary) egress containment (IPv6) ---",
    "-A ufw6-before-output -m owner --uid-owner opencanary -p udp -d ::1 --dport 53 -j ACCEPT",
    "-A ufw6-before-output -m owner --uid-owner opencanary -p tcp -d ::1 --dport 53 -j ACCEPT",
    "-A ufw6-before-output -m owner --uid-owner opencanary -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT",
    "-A ufw6-before-output -m owner --uid-owner opencanary -j REJECT",
])
PYCANARY
    fi

    # Agent home: the package creates ~/.config as root; give it back.
    if id tuxwall-agent >/dev/null 2>&1 && [[ -d /home/tuxwall-agent ]]; then
        chown -R tuxwall-agent:tuxwall-agent /home/tuxwall-agent
    fi

    # Install profile: lets later tooling (and future dashboard versions) know
    # the topology instead of guessing interface names.
    python3 - "$PROFILE_JSON" <<PY
import json, sys, datetime
data = {
    "installed_at": datetime.datetime.now().isoformat(timespec="seconds"),
    "installer": "$INSTALLER_VERSION",
    "source": "$SOURCE",
    "role": "$ROLE",
    "package_version": "$PKG_VERSION",
    "wan": "$WAN" or None,
    "wan_mode": "$WAN_MODE" or None,
    "lan": "$LAN" or None,
    "lan_network": "$NET_CIDR" or None,
    "lan_gateway": "$NET_GW" or None,
    "dhcp_pool": ["$NET_POOL_LO", "$NET_POOL_HI"] if "$NET_POOL_LO" else None,
    "ula_prefix": ("$ULA::/64" if "$ULA" else None),
    "domain": "$DOMAIN" or None,
}
with open(sys.argv[1], "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
PY
    chmod 644 "$PROFILE_JSON"
    ok "Install profile written to $PROFILE_JSON"
}

