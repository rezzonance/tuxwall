print_iface_table() {   # print_iface_table exclude
    local i=1 n tags v4
    for n in "${PHYS_IFACES[@]}"; do
        [[ $n == "${1:-}" ]] && continue
        tags=""
        [[ $n == "$DEF_IF" ]] && tags+=" ${C_B}[internet route]${C_0}"
        [[ $n == "$SSH_IFACE" ]] && tags+=" ${C_Y}[your SSH session]${C_0}"
        iface_wireless "$n" && tags+=" ${C_DIM}[wireless]${C_0}"
        v4="$(iface_v4 "$n")"
        printf '      %s%d)%s %-12s %s%-17s %-8s %s%s%s\n' "$C_C" "$i" "$C_0" "$n" "$C_DIM" \
            "$(iface_mac "$n")" "$(iface_link "$n")" "${v4:-no IPv4}" "$C_0" "$tags"
        i=$((i + 1))
    done
}

pick_iface() {   # pick_iface VAR "title" exclude default
    local __var=$1 title=$2 excl=$3 def=$4 list=() n ans idx=1 defidx=1
    for n in "${PHYS_IFACES[@]}"; do
        [[ $n == "$excl" ]] && continue
        list+=("$n")
        [[ $n == "$def" ]] && defidx=$idx
        idx=$((idx + 1))
    done
    (( ${#list[@]} )) || die "No interface left to choose for: $title"
    printf '\n  %s%s%s\n' "$C_BOLD" "$title" "$C_0"
    print_iface_table "$excl"
    while true; do
        ask ans "    Choose 1-${#list[@]} (Enter = ${list[$((defidx - 1))]}, q = quit):"
        ans=${ans:-$defidx}
        [[ $ans =~ ^[qQ]$ ]] && user_abort
        if [[ $ans =~ ^[0-9]+$ ]] && (( ans >= 1 && ans <= ${#list[@]} )); then
            printf -v "$__var" '%s' "${list[$((ans - 1))]}"
            return 0
        fi
        printf '    %sEnter a number between 1 and %d.%s\n' "$C_Y" "${#list[@]}" "$C_0"
    done
}

default_lan_subnet() {
    local cur avoid c
    mapfile -t avoid < <(other_networks "$LAN")
    cur="$(iface_v4 "$LAN" | awk '{print $1}')"
    if [[ -n $cur && $(net_calc "$cur" "${avoid[@]}") == OK* ]]; then
        echo "$cur"; return
    fi
    for c in 192.168.1.1/24 192.168.50.1/24 10.20.30.1/24 172.20.0.1/24; do
        if [[ $(net_calc "$c" "${avoid[@]}") == OK* ]]; then echo "$c"; return; fi
    done
    echo "192.168.1.1/24"
}

