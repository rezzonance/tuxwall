log()   { [[ -w "$LOG" ]] && printf '%s %s\n' "$(date '+%F %T')" "$*" >>"$LOG" || true; }
ok()    { printf '  %s✓%s %s\n' "$C_G" "$C_0" "$*"; log "OK   $*"; }
