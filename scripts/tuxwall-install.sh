detect_phys_ifaces() {
    PHYS_IFACES=()
    local p n
    for p in /sys/class/net/*; do
        n=${p##*/}
        [[ $n == lo ]] && continue
        [[ -e "$p/device" ]] || continue          # physical / virtio NICs only
        [[ -d "$p/bridge" || -d "$p/bonding" ]] && continue
        PHYS_IFACES+=("$n")
    done
    DEF_IF="$(ip -4 route show default 2>/dev/null | awk '{for (i=1;i<NF;i++) if ($i=="dev") {print $(i+1); exit}}' || true)"
}

iface_v4()   { { ip -4 -o addr show dev "$1" scope global 2>/dev/null || true; } | awk '{print $4}' | paste -sd' ' -; }
iface_mac()  { cat "/sys/class/net/$1/address" 2>/dev/null || true; }
iface_link() {
    local c; c="$(cat "/sys/class/net/$1/carrier" 2>/dev/null || echo 0)"
    [[ $c == 1 ]] && echo "link up" || echo "no link"
}
iface_wireless() { [[ -d "/sys/class/net/$1/wireless" || -e "/sys/class/net/$1/phy80211" ]]; }
iface_exists()   { [[ -e "/sys/class/net/$1" ]]; }

# Networks of every interface except $1 (used for overlap checks).
other_networks() {
    { ip -4 -o addr show scope global 2>/dev/null || true; } | awk -v skip="$1" '$2 != skip {print $4}'
}

detect_ssh() {
    local c="${SSH_CONNECTION:-}" pid=$$ parent
    # sudo drops SSH_CONNECTION; recover it from the parent processes.
    while [[ -z $c && $pid -gt 1 ]]; do
        parent="$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ' || true)"
        [[ -n $parent && $parent != "$pid" ]] || break
        pid=$parent
        [[ -r /proc/$pid/environ ]] || continue
        c="$( { tr '\0' '\n' <"/proc/$pid/environ"; } 2>/dev/null | sed -n 's/^SSH_CONNECTION=//p' | head -n1 || true)"
    done
    SSH_CONN="$c"
    [[ -n $c ]] || return 0
    read -r SSH_CLIENT_IP _ SSH_SERVER_IP SSH_SERVER_PORT <<<"$c"
    log "ssh session from $SSH_CLIENT_IP to $SSH_SERVER_IP:$SSH_SERVER_PORT"
    SSH_IFACE="$(ip -o addr show 2>/dev/null | awk -v ip="$SSH_SERVER_IP" '{split($4,a,"/"); if (a[1]==ip) {print $2; exit}}' || true)"
}

detect_ssh_ports() {
    SSH_PORTS=()
    local p
    if command -v sshd >/dev/null 2>&1 || [[ -x /usr/sbin/sshd ]]; then
        while read -r p; do
            [[ $p =~ ^[0-9]+$ ]] && SSH_PORTS+=("$p")
        done < <({ /usr/sbin/sshd -T 2>/dev/null || true; } | awk '$1=="port"{print $2}' | sort -un)
        (( ${#SSH_PORTS[@]} )) || SSH_PORTS=(22)
    fi
    if [[ -n $SSH_SERVER_PORT ]] && ! printf '%s\n' "${SSH_PORTS[@]}" | grep -qx "$SSH_SERVER_PORT"; then
        SSH_PORTS+=("$SSH_SERVER_PORT")
    fi
}

# net_calc CIDR [avoid-cidr ...] -> "OK|net|gw|mask|prefix|pool_lo|pool_hi" or "ERR|reason"
net_calc() {
    python3 - "$@" <<'PY'
import ipaddress, sys
raw = sys.argv[1].strip()
avoid = [a for a in sys.argv[2:] if a]
try:
    iface = ipaddress.ip_interface(raw if "/" in raw else raw + "/24")
except ValueError:
    print("ERR|not a valid IPv4 network (example: 192.168.1.1/24)"); sys.exit()
net = iface.network
if net.version != 4:
    print("ERR|use an IPv4 network for the LAN (IPv6 is added automatically)"); sys.exit()
if not net.is_private or net.is_loopback or net.is_link_local:
    print("ERR|the LAN must use a private range (10.x, 172.16-31.x or 192.168.x)"); sys.exit()
if not 16 <= net.prefixlen <= 29:
    print("ERR|use a prefix between /16 and /29 (a /24 suits most homes)"); sys.exit()
for a in avoid:
    try:
        other = ipaddress.ip_interface(a).network
    except ValueError:
        continue
    if net.overlaps(other):
        print("ERR|%s overlaps %s, which is already in use on another interface" % (net, other)); sys.exit()
gw = iface.ip if iface.ip != net.network_address else net.network_address + 1
if gw == net.broadcast_address:
    print("ERR|the gateway address cannot be the broadcast address"); sys.exit()
hosts = net.num_addresses - 2
first, last = net.network_address + 1, net.broadcast_address - 1
if hosts >= 200:
    lo, hi = net.network_address + 100, net.network_address + 199
else:
    lo, hi = first + hosts // 2, last
if lo <= gw <= hi:
    if gw == lo:
        lo += 1
    elif gw == hi:
        hi -= 1
    else:
        print("ERR|gateway %s falls inside the DHCP pool %s-%s; use .1 for the gateway" % (gw, lo, hi)); sys.exit()
print("OK|%s|%s|%s|%d|%s|%s" % (net, gw, net.netmask, net.prefixlen, lo, hi))
PY
}

valid_domain() {
    local d=$1
    [[ ${#d} -le 253 ]] || return 1
    [[ $d =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || return 1
    [[ $d != *.local && $d != local ]]
}

gen_ula() {
    local gid
    gid="$(od -An -tx1 -N5 /dev/urandom 2>/dev/null | tr -d ' \n')"
    [[ ${#gid} -eq 10 ]] || gid="$(printf '%010x' "$((RANDOM * RANDOM))")"
    printf 'fd%s:%s:%s' "${gid:0:2}" "${gid:2:4}" "${gid:6:4}"
}

existing_ula() {   # reuse the ULA from an existing radvd.conf
    [[ -f /etc/radvd.conf ]] || return 0
    sed -nE 's/^[[:space:]]*prefix[[:space:]]+(fd[0-9a-f]{2}:[0-9a-f]{1,4}:[0-9a-f]{1,4})::\/64.*/\1/p' /etc/radvd.conf | head -n1 || true
}

kea_is_replaceable() {
    local f=/etc/kea/kea-dhcp4.conf
    [[ ! -s $f ]] && return 0
    grep -q "$INSTALLER_MARK" "$f" && return 0
    grep -q '192\.0\.2\.' "$f" && return 0          # Kea's shipped sample config
    return 1
}
radvd_is_replaceable()   { [[ ! -s /etc/radvd.conf ]] || grep -q "$INSTALLER_MARK" /etc/radvd.conf; }
unbound_is_replaceable() {
    local f=/etc/unbound/unbound.conf.d/router-dns.conf
    [[ ! -s $f ]] || grep -q "$INSTALLER_MARK" "$f"
}

backup_file() {
    [[ -e $1 ]] || return 0
    mkdir -p "$BACKUP_DIR$(dirname "$1")"
    cp -a "$1" "$BACKUP_DIR$1"
    log "backup $1 -> $BACKUP_DIR$1"
}

ufw_has_ssh_rule() {
    local p=$1 added
    added="$(ufw show added 2>/dev/null | grep -E '^ufw (allow|limit)' || true)"
    grep -Eq "(^|[[:space:]])${p}(/tcp)?([[:space:]]|$)|port ${p}([[:space:]]|$)" <<<"$added" && return 0
    [[ $p == 22 ]] && grep -qi 'openssh' <<<"$added" && return 0
    return 1
}

