    mkdir -p /etc/kea
    tmp="$(mktemp -p /etc/kea .tuxwall-kea-dhcp4.XXXXXX)"
    for key in socket-name socket-address; do
        kea_json "$key" >"$tmp"
        if ! command -v kea-dhcp4 >/dev/null 2>&1 || q kea-dhcp4 -t "$tmp"; then
            chosen=$key; break
        fi
    done
    if [[ -z $chosen ]]; then
        rm -f "$tmp"
        warn "Kea rejected the generated config (see $LOG); kept the existing file."
        return 0
    fi
    getent group _kea >/dev/null 2>&1 && grp=_kea
    getent group kea  >/dev/null 2>&1 && grp=kea
    backup_file "$f"
    install -o root -g "$grp" -m 640 "$tmp" "$f"
    rm -f "$tmp"
    ok "Kea DHCP: $NET_CIDR on $LAN, pool $NET_POOL_LO – $NET_POOL_HI"
}

