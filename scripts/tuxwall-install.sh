gather_config() {
    local c ans r avoid=()

    # ── Source ───────────────────────────────────────────────────────────────
    if [[ -z $SOURCE ]]; then
        local def=2; have_repo && def=1
        if (( INTERACTIVE )); then
            local local_desc="this folder is not a TuxWall source checkout"
            have_repo && local_desc="build $(repo_version) from $REPO_DIR"
            menu c "Where should TuxWall come from?" "$def" \
                "This folder (source)|$local_desc" \
                "Official APT repository|signed, latest release" \
                "A .deb file|a tuxwall_*.deb you already have"
            case "$c" in 1) SOURCE=local ;; 2) SOURCE=apt ;; 3) SOURCE=deb ;; esac
        else
            SOURCE=apt; have_repo && SOURCE=local
        fi
    fi
    if [[ $SOURCE == local ]] && ! have_repo; then
        die "--source local needs the TuxWall source tree next to this script ($REPO_DIR)."
    fi
    if [[ $SOURCE == deb && -z $DEB_FILE ]]; then
        local found; found="$(find "$REPO_DIR" -maxdepth 1 -name 'tuxwall*_all.deb' 2>/dev/null | sort -V | tail -n1)"
        if (( INTERACTIVE )); then
            ask DEB_FILE "    Path to the .deb${found:+ (Enter = $found)}:"
            DEB_FILE=${DEB_FILE:-$found}
        else
            DEB_FILE=$found
        fi
    fi
    if [[ $SOURCE == deb ]]; then
        [[ -f $DEB_FILE ]] || die "Package file not found: ${DEB_FILE:-<none given>}"
        DEB_FILE="$(readlink -f "$DEB_FILE")"
        [[ "$(dpkg-deb -f "$DEB_FILE" Package 2>/dev/null || true)" == tuxwall ]] || die "$DEB_FILE is not a tuxwall package."
    fi

    # ── Role ─────────────────────────────────────────────────────────────────
    if [[ -z $ROLE ]]; then
        local rdef=1; (( ${#PHYS_IFACES[@]} < 2 )) && rdef=2
        if (( INTERACTIVE )); then
            (( ${#PHYS_IFACES[@]} < 2 )) && note "Only ${#PHYS_IFACES[@]} network interface found; a gateway needs two (WAN + LAN)."
            menu c "How will this machine be used?" "$rdef" \
                "Full gateway|TuxWall routes your network: WAN/LAN, DHCP, DNS, NAT" \
                "Dashboard only|don't set up WAN/LAN, DHCP or DNS on this machine"
            [[ $c == 1 ]] && ROLE=gateway || ROLE=dashboard
        else
            [[ $rdef == 1 ]] && ROLE=gateway || ROLE=dashboard
        fi
    fi

    if [[ $ROLE == gateway ]]; then
        (( ${#PHYS_IFACES[@]} >= 2 )) || warn "Gateway mode with fewer than two physical interfaces: double-check the WAN/LAN choice."

        # WAN
        if [[ -z $WAN ]]; then
            local wdef="${DEF_IF:-${PHYS_IFACES[0]:-}}"
            if (( INTERACTIVE )); then
                pick_iface WAN "Which interface faces the internet (WAN)?" "" "$wdef"
            else
                [[ -n $wdef ]] || die "Cannot detect the WAN interface; pass --wan."
                WAN=$wdef
            fi
        fi
        iface_exists "$WAN" || die "Interface not found: $WAN"

        # WAN mode
        if [[ -z $WAN_MODE ]]; then
            if [[ -n "$(iface_v4 "$WAN")" ]] || iface_wireless "$WAN"; then WAN_MODE=keep; else WAN_MODE=dhcp; fi
            if (( INTERACTIVE )) && [[ $WAN_MODE == keep ]] && ! iface_wireless "$WAN"; then
                menu c "WAN addressing ($WAN currently has $(iface_v4 "$WAN"))" 1 \
                    "Keep current config|leave $WAN exactly as it is (recommended)" \
                    "DHCP from the ISP|let TuxWall configure $WAN for DHCP v4 + v6"
                [[ $c == 1 ]] && WAN_MODE=keep || WAN_MODE=dhcp
            fi
        fi
        if [[ $WAN_MODE == dhcp ]] && iface_wireless "$WAN"; then
            warn "$WAN is wireless; leaving its configuration as it is."
            WAN_MODE=keep
        fi

        # LAN
        if [[ -z $LAN ]]; then
            local ldef="" n
            for n in "${PHYS_IFACES[@]}"; do
                [[ $n == "$WAN" ]] && continue
                [[ -z $ldef ]] && ldef=$n
                [[ "$(iface_link "$n")" == "link up" ]] && { ldef=$n; break; }
            done
            if (( INTERACTIVE )); then
                pick_iface LAN "Which interface connects to your local network (LAN)?" "$WAN" "$ldef"
            else
                local others=0
                for n in "${PHYS_IFACES[@]}"; do [[ $n != "$WAN" ]] && others=$((others + 1)); done
                (( others == 1 )) || die "Several LAN candidates; pass --lan IFACE."
                LAN=$ldef
            fi
        fi
        iface_exists "$LAN" || die "Interface not found: $LAN"
        [[ $LAN != "$WAN" ]] || die "WAN and LAN must be different interfaces."
        iface_wireless "$LAN" && die "$LAN is a wireless interface; the LAN must be wired (use an access point)."

        # LAN subnet
        mapfile -t avoid < <(other_networks "$LAN")
        [[ -n $LAN_SUBNET ]] || LAN_SUBNET="$(default_lan_subnet)"
        while true; do
            if (( INTERACTIVE )); then
                printf '\n  %sLAN network%s %s(the address you type becomes the gateway)%s\n' "$C_BOLD" "$C_0" "$C_DIM" "$C_0"
                ask ans "    LAN address/prefix (Enter = $LAN_SUBNET):"
                [[ $ans =~ ^[qQ]$ ]] && user_abort
                [[ -n $ans ]] && LAN_SUBNET=$ans
            fi
            r="$(net_calc "$LAN_SUBNET" "${avoid[@]}")"
            if [[ $r == OK* ]]; then
                IFS='|' read -r _ NET_CIDR NET_GW NET_MASK NET_PREFIX NET_POOL_LO NET_POOL_HI <<<"$r"
                break
            fi
            (( INTERACTIVE )) || die "LAN network $LAN_SUBNET: ${r#ERR|}"
            printf '    %s%s%s\n' "$C_Y" "${r#ERR|}" "$C_0"
            LAN_SUBNET="$(default_lan_subnet)"
        done

        # Domain
        DOMAIN=${DOMAIN:-home.arpa}
        while true; do
            if (( INTERACTIVE )); then
                ask ans "    Local DNS domain (Enter = $DOMAIN):"
                [[ $ans =~ ^[qQ]$ ]] && user_abort
                [[ -n $ans ]] && DOMAIN="${ans,,}"
            fi
            DOMAIN="${DOMAIN%.}"
            valid_domain "$DOMAIN" && break
            (( INTERACTIVE )) || die "Invalid domain: $DOMAIN"
            printf '    %sUse at least two labels, e.g. home.arpa or lan.example.com (not .local).%s\n' "$C_Y" "$C_0"
            DOMAIN=home.arpa
        done

        ULA="$(existing_ula)"; [[ -n $ULA ]] || ULA="$(gen_ula)"

        # Existing service configs
        if kea_is_replaceable; then KEA_ACTION="write"
        elif (( FORCE_NET )); then KEA_ACTION=replace
        elif (( INTERACTIVE )) && confirm "/etc/kea/kea-dhcp4.conf is already customised. Replace it (a backup is kept)?" n; then KEA_ACTION=replace
        else KEA_ACTION=keep; fi

        if radvd_is_replaceable; then RADVD_ACTION="write"
        elif (( FORCE_NET )); then RADVD_ACTION=replace
        else RADVD_ACTION=keep; fi

        if unbound_is_replaceable; then UNBOUND_ACTION="write"
        elif (( FORCE_NET )); then UNBOUND_ACTION=replace
        else UNBOUND_ACTION=keep; fi

        # SSH scope: keep remote admins connected.
        if [[ -n $SSH_IFACE && $SSH_IFACE != "$LAN" ]]; then SSH_SCOPE=any; else SSH_SCOPE=lan; fi

        decide_network_apply
    else
        SSH_SCOPE=any
        [[ -n $DOMAIN ]] || DOMAIN=home.arpa
    fi

    [[ $SOURCE == apt ]] && WITH_APT_REPO=1
    (( INTERACTIVE )) && toggle_components
    return 0
}

decide_network_apply() {
    local cur_lan_ips
    cur_lan_ips="$(iface_v4 "$LAN")"
    case "$APPLY_NET" in
        now)    NET_APPLY_DECISION=now; NET_APPLY_REASON="requested with --apply-network now" ;;
        reboot) NET_APPLY_DECISION=reboot; NET_APPLY_REASON="requested with --apply-network reboot" ;;
        auto)
            if (( FROM_CONSOLE )) || [[ -z $SSH_CONN ]]; then
                NET_APPLY_DECISION=now; NET_APPLY_REASON="no SSH session to protect"
            elif [[ $SSH_IFACE == "$LAN" && " $cur_lan_ips " != *" $NET_GW/"* ]]; then
                NET_APPLY_DECISION=reboot
                NET_APPLY_REASON="your SSH session uses $LAN, whose address will change to $NET_GW"
            elif [[ $SSH_IFACE == "$WAN" && $WAN_MODE == dhcp ]]; then
                NET_APPLY_DECISION=reboot
                NET_APPLY_REASON="your SSH session uses $WAN, which is being switched to DHCP"
            else
                NET_APPLY_DECISION=now; NET_APPLY_REASON="your SSH session is not affected"
            fi ;;
    esac
}

