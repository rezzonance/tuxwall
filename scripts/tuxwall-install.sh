parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --source)            SOURCE="${2:-}"; shift 2 ;;
            --deb)               DEB_FILE="${2:-}"; SOURCE=deb; shift 2 ;;
            --role)              ROLE="${2:-}"; shift 2 ;;
            --wan)               WAN="${2:-}"; shift 2 ;;
            --lan)               LAN="${2:-}"; shift 2 ;;
            --wan-mode)          WAN_MODE="${2:-}"; shift 2 ;;
            --subnet)            LAN_SUBNET="${2:-}"; shift 2 ;;
            --domain)            DOMAIN="${2:-}"; shift 2 ;;
            --replace-configs)   FORCE_NET=1; shift ;;
            --apply-network)     APPLY_NET="${2:-}"; shift 2 ;;
            --no-crowdsec)       WITH_CROWDSEC=0; shift ;;
            --no-agent)          WITH_AGENT=0; shift ;;
            --no-speedtest)      WITH_SPEEDTEST=0; shift ;;
            --no-geoip)          WITH_GEOIP=0; shift ;;
            --no-apt-repo)       WITH_APT_REPO=0; shift ;;
            --agent-edit-webroot) AGENT_EDIT_WEBROOT=1; shift ;;
            --dry-run)           DRY_RUN=1; shift ;;
            --console)           CONSOLE_STAGE=1; shift ;;
            --from-console)      FROM_CONSOLE=1; shift ;;
            --disable-multipath) DISABLE_MULTIPATH=1; shift ;;
            -y|--yes)            ASSUME_YES=1; shift ;;
            -h|--help)           usage; exit 0 ;;
            *)                   usage >&2; printf '\nUnknown option: %s\n' "$1" >&2; exit 1 ;;
        esac
    done
    case "$SOURCE" in ""|local|apt|deb) ;; *) die "--source must be local, apt or deb" ;; esac
    case "$ROLE" in ""|gateway|dashboard) ;; *) die "--role must be gateway or dashboard" ;; esac
    case "$WAN_MODE" in ""|keep|dhcp) ;; *) die "--wan-mode must be keep or dhcp" ;; esac
    case "$APPLY_NET" in auto|now|reboot) ;; *) die "--apply-network must be now, reboot or auto" ;; esac
}

