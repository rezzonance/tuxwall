unbound_gateway_conf() {
    cat <<UNB
# $INSTALLER_MARK on $(date '+%F %T').
server:
    local-zone: "$DOMAIN." static
    local-data: "gateway.$DOMAIN. IN A $NET_GW"
    local-data: "gateway.$DOMAIN. IN AAAA $ULA::1"
